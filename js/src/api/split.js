import { handleSplit } from '../../vendor/redocly-cli/commands/split/index.js';
import * as path from 'node:path';
import { captureOutput } from '../polyfills.js';

/**
 * @param opts {{ cwd: string, api: string, outDir: string, separator?: string, fileNameConflictsSeverity?: 'warn'|'error'|'off' }}
 * @returns the progress lines (`output`) apart from the codeframes of the file name conflicts (`problems`), which
 *   the command prints on the same channel
 */
export async function runSplit(opts) {
  const api = path.resolve(opts.cwd, opts.api);
  const outDir = path.resolve(opts.cwd, opts.outDir);
  const argv = { api, outDir, separator: opts.separator || '_', 'file-name-conflicts-severity': opts.fileNameConflictsSeverity || 'warn' };
  const { entries } = await captureOutput(() => handleSplit({ argv, version: '' }));
  const isProblem = (entry) => SPLIT_PROBLEM.test(entry.text);
  const text = (selected) => selected.map((entry) => entry.text).join('');
  return { api, outDir, output: text(entries.filter((entry) => !isProblem(entry))), problems: text(entries.filter(isProblem)) };
}

const SPLIT_PROBLEM = /(Warning|Error) was generated by the split rule\.\s*$/;
